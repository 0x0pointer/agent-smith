<#
.SYNOPSIS
    Put the `smith` control-plane command on PATH (Windows / PowerShell port of
    install-smith-cli.sh).

.DESCRIPTION
    pyproject.toml declares `smith = "smith_cli:main"`, but the project is
    package-mode = false, so `poetry install` never materialises that script.
    This writes a small smith.cmd launcher that resolves the project virtualenv
    through run-mcp-server.ps1 --print-python (the same resolver the MCP server
    uses), so `smith start | stop | status` works from any directory, in cmd.exe
    and in PowerShell.

    Install location: $env:SMITH_BIN_DIR, default ~\.local\bin. The launcher is
    never written over a smith.cmd this script did not create.

.EXAMPLE
    .\install-smith-cli.ps1                # install (asks before touching PATH)
    .\install-smith-cli.ps1 -AddToPath     # install and add the folder to the user PATH
    .\install-smith-cli.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [switch]$Uninstall,
    [switch]$AddToPath
)

$ErrorActionPreference = 'Stop'

$RepoDir  = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$BinDir   = if ($env:SMITH_BIN_DIR) { $env:SMITH_BIN_DIR } else { Join-Path $env:USERPROFILE '.local\bin' }
$Launcher = Join-Path $BinDir 'smith.cmd'
$Marker   = 'agent-smith control-plane launcher'

function Write-Ok   { param([string]$m) Write-Host "OK   $m" -ForegroundColor Green }
function Write-Warn { param([string]$m) Write-Host "WARN $m" -ForegroundColor Yellow }

function Test-Ours {
    if (-not (Test-Path $Launcher)) { return $false }
    return [bool](Select-String -Path $Launcher -SimpleMatch $Marker -Quiet)
}

if ($Uninstall) {
    if (Test-Ours) {
        Remove-Item -Path $Launcher -Force
        Write-Ok "smith launcher removed ($Launcher)"
    }
    exit 0
}

# Never clobber an unrelated `smith` the operator already has there.
if ((Test-Path $Launcher) -and -not (Test-Ours)) {
    Write-Warn "$Launcher exists and is not the agent-smith launcher - leaving it alone."
    Write-Warn "Run the control plane with: poetry -C `"$RepoDir`" run python `"$RepoDir\smith_cli.py`" start"
    exit 0
}

New-Item -ItemType Directory -Path $BinDir -Force | Out-Null

# cmd.exe reads batch files in the OEM code page, so keep the launcher ASCII.
# setlocal restores the caller's directory and variables when it ends.
$resolver = Join-Path $RepoDir 'installers\run-mcp-server.ps1'
$content = @(
    '@echo off'
    "rem $Marker (generated by installers\install-smith-cli.ps1 - re-run the installer to update)"
    'setlocal'
    "set `"REPO_DIR=$RepoDir`""
    'if not exist "%REPO_DIR%\smith_cli.py" ('
    '    echo smith: agent-smith checkout not found at %REPO_DIR% - re-run its installer. 1>&2'
    '    exit /b 1'
    ')'
    'set "SMITH_PY="'
    "for /f `"usebackq delims=`" %%P in (``powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$resolver`" --print-python``) do set `"SMITH_PY=%%P`""
    'if not defined SMITH_PY ('
    '    echo smith: could not resolve the agent-smith virtualenv - run: poetry -C "%REPO_DIR%" install 1>&2'
    '    exit /b 1'
    ')'
    'set "PYTHONPATH=%REPO_DIR%"'
    'set "PYTHONUTF8=1"'
    'cd /d "%REPO_DIR%"'
    '"%SMITH_PY%" "%REPO_DIR%\smith_cli.py" %*'
    'exit /b %ERRORLEVEL%'
) -join "`r`n"
[System.IO.File]::WriteAllText($Launcher, $content + "`r`n", (New-Object System.Text.ASCIIEncoding))
Write-Ok "smith command installed: $Launcher  (smith start | stop | status)"

# PATH: the bash installer only warns; on Windows there is no shell rc file to
# point at, so offer to add the folder to the USER Path (never the machine Path).
$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
$onPath = (($userPath -split ';') + ($env:Path -split ';')) |
          Where-Object { $_ -and ($_.TrimEnd('\') -ieq $BinDir.TrimEnd('\')) }
if (-not $onPath) {
    $add = $AddToPath
    if (-not $add -and [Environment]::UserInteractive) {
        try {
            $ans = Read-Host "  $BinDir is not on your PATH. Add it to your user PATH? [Y/n]"
            $add = ($ans -eq '' -or $ans -match '^[Yy]')
        } catch { $add = $false }
    }
    if ($add) {
        $newPath = if ($userPath) { "$($userPath.TrimEnd(';'));$BinDir" } else { $BinDir }
        [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
        $env:Path = "$env:Path;$BinDir"
        Write-Ok "$BinDir added to your user PATH (open a new terminal to pick it up)"
    } else {
        Write-Warn "$BinDir is not on your PATH - add it, or run: & `"$Launcher`" start"
    }
}
