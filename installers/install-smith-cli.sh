#!/usr/bin/env bash
# install-smith-cli.sh — put the `smith` control-plane command on PATH.
#
# Usage: install-smith-cli.sh [--uninstall]
#
# pyproject.toml declares `smith = "smith_cli:main"`, but the project is
# `package-mode = false`, so `poetry install` never materialises that script.
# Without this launcher the only way to reach the control plane is
# `poetry run python smith_cli.py ...` from inside the checkout. The launcher
# resolves the project virtualenv through run-mcp-server.sh (the same resolver
# the MCP server uses), so it works from any directory and any shell.
#
# Install location: $SMITH_BIN_DIR, default ~/.local/bin.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_DIR="${SMITH_BIN_DIR:-$HOME/.local/bin}"
LAUNCHER="$BIN_DIR/smith"
MARKER="# agent-smith control-plane launcher"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
ok()   { echo -e "${GREEN}✓${NC} $*"; }
warn() { echo -e "${YELLOW}⚠${NC}  $*"; }

_is_ours() { [[ -f "$LAUNCHER" ]] && grep -qF "$MARKER" "$LAUNCHER" 2>/dev/null; }

if [[ "${1:-}" == "--uninstall" ]]; then
    if _is_ours; then
        rm -f "$LAUNCHER"
        ok "smith launcher removed ($LAUNCHER)"
    fi
    exit 0
fi

# Never clobber an unrelated `smith` binary the operator already has there.
if [[ -e "$LAUNCHER" ]] && ! _is_ours; then
    warn "$LAUNCHER exists and is not the agent-smith launcher — leaving it alone."
    warn "Run the control plane with: poetry -C \"$REPO_DIR\" run python \"$REPO_DIR/smith_cli.py\" start"
    exit 0
fi

mkdir -p "$BIN_DIR"
{
    echo '#!/usr/bin/env bash'
    echo "$MARKER (generated by installers/install-smith-cli.sh — re-run the installer to update)"
    printf 'REPO_DIR=%q\n' "$REPO_DIR"
    cat <<'LAUNCHER_EOF'
# GUI-launched shells can omit the locations docker / poetry live in.
export PATH="$PATH:/usr/local/bin:/opt/homebrew/bin:/snap/bin:/Applications/Docker.app/Contents/Resources/bin"
if [[ ! -f "$REPO_DIR/smith_cli.py" ]]; then
    echo "smith: agent-smith checkout not found at $REPO_DIR — re-run its installer." >&2
    exit 1
fi
PYTHON="$("$REPO_DIR/installers/run-mcp-server.sh" --print-python)" || exit 1
cd "$REPO_DIR"
exec env PYTHONPATH="$REPO_DIR" "$PYTHON" "$REPO_DIR/smith_cli.py" "$@"
LAUNCHER_EOF
} > "$LAUNCHER"
chmod +x "$LAUNCHER" "$REPO_DIR/installers/run-mcp-server.sh"
ok "smith command installed: $LAUNCHER  (smith start | stop | status)"

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) warn "$BIN_DIR is not on your PATH — add it:  export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac
